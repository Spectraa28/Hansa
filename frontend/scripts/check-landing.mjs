// Saved evidence and mocked authentication only. No imported code or model calls run.
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const skill = process.argv[2]
assert(skill, 'Pass the installed browser helper directory.')
const base = process.argv[3] || 'http://localhost:5173'
const out = process.argv[4] || '/tmp/hansa-light-laboratory'
await fs.mkdir(out, { recursive: true })
const report = JSON.parse(await fs.readFile(new URL('../src/data/swarm-report.json', import.meta.url), 'utf8'))
const patches = JSON.parse(await fs.readFile(new URL('../src/data/swarm-patches.json', import.meta.url), 'utf8'))
const { launch } = await import(pathToFileURL(path.join(skill, 'scripts/lib/browser.mjs')))
const scanner = await fs.readFile(path.join(skill, 'scripts/lib/inpage.js'), 'utf8')
const { browser } = await launch()
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
await context.route(`${base}/auth/me`, route => route.fulfill({ status: 401, json: { detail: 'Sign in to continue.' } }))
await context.route(`${base}/auth/providers`, route => route.fulfill({ json: { github: true, google: false, email: false } }))
const requests = [], errors = []
context.on('request', request => { if (request.method() !== 'GET' || new URL(request.url()).pathname.startsWith('/github/')) requests.push(request.url()) })
const page = await context.newPage()
page.on('pageerror', error => errors.push(error.message))
page.setDefaultTimeout(10000)

try {
  await page.goto(base)
  await page.getByRole('heading', { level: 1 }).waitFor()
  await page.evaluate(() => document.fonts.ready)
  await page.waitForTimeout(850)
  await page.screenshot({ path: path.join(out, 'hero-desktop.png') })
  assert.match(await page.locator('h1').innerText(), /An optimization engineer for your AI agent\./)
  assert.equal(await page.locator('.hero-actions .button-primary').getAttribute('href'), '/app/new')
  const fieldSize = await page.evaluate(() => {
    const input = document.createElement('input')
    input.className = 'field text-[15px]'
    document.body.append(input)
    const size = getComputedStyle(input).fontSize
    input.remove()
    return size
  })
  assert.equal(fieldSize, '16px', 'Editable fields retain a 16px floor')
  assert.deepEqual(await page.locator('.landing > section').evaluateAll(elements => elements.map(el => el.id || 'hero')), ['hero', 'real-run', 'how-it-works'])
  assert.equal(await page.locator('.process-flow > li').count(), 4)
  assert.equal(await page.locator('.artifact-repo').getAttribute('href'), `https://github.com/${report.import.repository}/tree/${report.import.commit_sha}`)
  assert.equal(await page.locator('.artifact-call-bars i').count(), Math.round(report.baseline.per_pass.model_calls))
  const actualDiffLine = patches[report.optimizations.at(-1).job_id].split('\n').find(line => line.startsWith('+') && !line.startsWith('+++'))
  assert.equal(await page.locator('.artifact-diff').getAttribute('title'), actualDiffLine)
  assert.equal(await page.locator('.artifact-diff').getAttribute('href'), '/demo?step=fix')
  assert.match(await page.locator('.artifact-verdict').innerText(), /Rejected\s+1 task regressed/)
  assert.equal(await page.locator('.hero .eyebrow, .section-heading .eyebrow, .process-flow .tile-tag, .landing-footer .eyebrow').count(), 0)
  assert.equal(await page.locator('.landing > :last-child').evaluate(el => el.tagName), 'FOOTER')
  assert.equal(await page.locator('.landing > *').evaluateAll(elements => elements.filter(el => getComputedStyle(el).backgroundColor === 'rgb(24, 36, 50)').length), 1, 'Exactly one major block uses deep ink')
  assert.equal(await page.locator('.landing-footer h2').evaluate(el => getComputedStyle(el).color), 'rgb(247, 249, 252)')
  assert.equal(await page.locator('.saved-demo').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(255, 255, 255)', 'Recorded proof retains its light surface')
  const depth = await page.locator('.experiment-diagram, .saved-demo').evaluateAll(elements => elements.map(el => ({ border: getComputedStyle(el).borderTopWidth, shadow: getComputedStyle(el).boxShadow })))
  assert(depth.every(surface => surface.border === '0px' && surface.shadow !== 'none'), 'Both proof surfaces use shadows instead of borders')
  assert.equal(depth[0].shadow, depth[1].shadow, 'Proof surfaces share the same layered depth')
  const stepBorders = await page.locator('.process-flow, .process-flow li').evaluateAll(elements => elements.map(el => ['Top', 'Right', 'Bottom', 'Left'].map(side => getComputedStyle(el)[`border${side}Width`])))
  assert(stepBorders.flat().every(width => width === '0px'), 'Connected steps have no card borders')
  const outsideMono = await page.evaluate(() => [...document.querySelectorAll('.landing *')].filter(el => !el.closest('.experiment-diagram, .saved-demo, .step-artifact') && [...el.childNodes].some(node => node.nodeType === Node.TEXT_NODE && node.textContent.trim()) && /mono/i.test(getComputedStyle(el).fontFamily)).map(el => el.textContent.trim()))
  assert.deepEqual(outsideMono, [], 'Marketing content uses the main font; mono stays inside product blocks')
  assert.equal(await page.locator('.parameter-grid').count(), 0)
  assert.match(await page.locator('.diagram-input').innerText(), /40 calls, \$0\.22/)
  assert.match(await page.locator('.diagram-verdict').innerText(), /−10% calls\s+1 task regressed\s+Rejected/)
  assert.match(await page.locator('.diagram-note').innerText(), /Recorded results/)
  assert.deepEqual(await page.locator('.recorded-metrics dt').allTextContents(), ['Cost', 'Latency', 'Model calls', 'Context', 'Task behavior', 'Run conditions'])
  const readings = await page.locator('.recorded-metrics dd').allTextContents()
  assert(readings[0].includes('$0.22 → $0.21'))
  assert(readings[1].includes('114 s → 102 s'))
  assert(readings[2].includes('40 → 36'))
  assert(readings[3].includes('53,886 → 51,241') && readings[3].includes('2,820 → 2,436'))
  assert(readings[4].includes('1 task regressed') && readings[4].includes('5 candidate answers need human review'))
  assert(readings[5].includes('6 tasks × 2 repetitions') && readings[5].includes('Spend/runtime caps not recorded'))
  assert.deepEqual(await page.locator('.metric-change').allTextContents(), ['−7%', '−10%', '−10%', '−5%'])
  assert.equal(await page.locator('.metric-change.text-ok').count(), 4, 'Only measured resource savings receive green percentages')
  assert.match(await page.locator('.recorded-measurements > p').innerText(), /Mean per pass.*not invoice-reconciled/)
  assert.equal(await page.locator('#real-run #what-it-checks').count(), 1, 'Measurements belong to the recorded experiment')
  assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).colorScheme), 'light')
  assert.match(await page.locator('.demo-panel').innerText(), /2 tasks with failed checks · 4 needing review/)
  assert.equal(await page.locator('.task-list > div').count(), report.baseline.tasks.length)

  // Keyboard operation follows the WAI-ARIA horizontal tab pattern.
  await page.getByRole('tab', { name: /Baseline/ }).focus()
  await page.keyboard.press('ArrowRight')
  assert.equal(await page.getByRole('tab', { name: /Findings/ }).getAttribute('aria-selected'), 'true')
  assert.equal(await page.locator('.demo-findings li').count(), report.investigation.findings.length)
  assert.match(await page.locator('.demo-panel').innerText(), /hypotheses, not measured gains/)
  await page.locator('.demo-findings summary').first().click()
  const source = report.investigation.findings[0].source[0]
  assert.equal(await page.locator('.finding-sources a').first().getAttribute('href'), `https://github.com/${report.import.repository}/blob/${report.import.commit_sha}/${source.path}#L${source.start_line}-L${source.end_line}`)
  await page.getByRole('tab', { name: /Findings/ }).focus()
  await page.keyboard.press('End')
  assert.equal(await page.getByRole('tab', { name: /Verdict/ }).getAttribute('aria-selected'), 'true')
  assert.match(await page.locator('.demo-panel').innerText(), /Cheaper and faster. Still rejected/)
  assert.match(await page.locator('.demo-panel').innerText(), /Lower resource usage does not establish correct answers/)
  assert.equal(await page.locator('.task-list .outcome-warning').count(), report.optimizations.at(-1).comparison.tasks.filter(task => task.regressed).length)
  for (const key of ['model_calls', 'cost_usd', 'wall_time_seconds']) assert((await page.locator('.demo-comparison').innerText()).includes(`${Math.abs(Math.round(report.optimizations.at(-1).comparison.totals[key].change_percent))}%`))
  const comparisonText = await page.locator('.demo-comparison').innerText()
  assert(comparisonText.includes('$0.22') && comparisonText.includes('$0.21') && comparisonText.includes('114 s') && comparisonText.includes('102 s'))
  assert(!comparisonText.includes('$0.2243538') && !comparisonText.includes('113.87 s'))
  await page.keyboard.press('Home')
  assert.equal(await page.getByRole('tab', { name: /Baseline/ }).getAttribute('aria-selected'), 'true')

  for (const width of [320, 375, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: width < 640 ? 844 : 900 })
    await page.goto(base)
    await page.evaluate(() => document.fonts.ready)
    await page.waitForTimeout(850)
    const intros = await page.locator('.section-heading').evaluateAll(elements => elements.map(el => {
      const heading = el.querySelector('h2').getBoundingClientRect(), intro = el.querySelector('p').getBoundingClientRect()
      return { headingLeft: heading.left, headingBottom: heading.bottom, introLeft: intro.left, introTop: intro.top }
    }))
    assert(intros.every(intro => intro.introLeft === intro.headingLeft && intro.introTop >= intro.headingBottom + 16), `${width}px: introductions sit beneath their headings`)
    const flow = await page.locator('.process-flow > li').evaluateAll(elements => elements.map(el => ({ top: el.getBoundingClientRect().top, connector: getComputedStyle(el, '::before').width })))
    if (width >= 1024) assert(flow.every(step => step.top === flow[0].top) && flow.slice(0, 3).every(step => Number.parseFloat(step.connector) > 32), `${width}px: one connected horizontal sequence`)
    else assert(flow.slice(0, 3).every(step => step.connector === '1px'), `${width}px: connected vertical sequence`)
    const smallCopy = await page.locator('.landing *').evaluateAll(elements => elements.filter(el => el.getBoundingClientRect().width > 0 && el.getBoundingClientRect().height > 0 && [...el.childNodes].some(node => node.nodeType === Node.TEXT_NODE && node.textContent.trim()) && Number.parseFloat(getComputedStyle(el).fontSize) < 14).map(el => el.textContent.trim().slice(0, 80)))
    assert.deepEqual(smallCopy, [], `${width}px: all visible copy is at least 14px`)
    const figureSizes = await page.locator('.metric-value').evaluateAll(elements => elements.map(el => Number.parseFloat(getComputedStyle(el).fontSize)))
    assert(figureSizes.every(size => size >= 32 && size <= 40), `${width}px: proof figures are 32–40px`)
    const figurePairs = await page.locator('.metric-figure').evaluateAll(elements => elements.slice(0, 3).map(el => {
      const value = el.querySelector('.metric-value').getBoundingClientRect(), delta = el.querySelector('.metric-change').getBoundingClientRect()
      return { valueRight: value.right, deltaLeft: delta.left, valueTop: value.top, deltaTop: delta.top }
    }))
    if (width >= 1024) assert(figurePairs.every(pair => pair.deltaLeft >= pair.valueRight && Math.abs(pair.deltaTop - pair.valueTop) < 30), `${width}px: changes sit beside the primary figures`)
    const proof = await page.locator('.hero-footnote').boundingBox()
    assert(proof.y + proof.height <= page.viewportSize().height, `${width}px: a real measured figure appears on the first screen`)
    for (const view of ['Baseline', 'Findings', 'Tested change', 'Verdict']) {
      await page.getByRole('tab', { name: new RegExp(view) }).click()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${width}px ${view}: no page overflow`)
      await page.evaluate(scanner)
      const scan = await page.evaluate(() => window.__wd.scan({ app: true }))
      if (scan.fails.length) await page.screenshot({ path: path.join(out, `failure-${width}.png`), fullPage: true })
      assert.deepEqual(scan.fails, [], `${width}px ${view}: readable layout and contrast`)
    }
    await page.getByRole('tab', { name: /Baseline/ }).click()
    await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }))
    await page.screenshot({ path: path.join(out, `landing-${width}.png`), fullPage: true })
    if (width === 375 || width === 1440) {
      await page.getByRole('tab', { name: /Verdict/ }).click()
      await page.locator('.saved-demo').screenshot({ path: path.join(out, `verdict-${width}.png`) })
    }
  }
  await page.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await page.locator('.experiment-diagram').evaluate(el => getComputedStyle(el).animationName), 'none')
  assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior), 'auto')
  await page.getByRole('link', { name: 'Measurements', exact: true }).click()
  assert.equal(new URL(page.url()).hash, '#what-it-checks')
  await page.getByRole('link', { name: 'Demo run', exact: true }).click()
  assert.equal(new URL(page.url()).hash, '#real-run')
  await page.locator('.demo-bottomline').getByRole('link').click()
  await page.waitForURL('**/demo?step=result')
  await page.getByText("You're looking at a real, saved run", { exact: true }).waitFor()
  for (const width of [375, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    for (const step of ['import', 'setup', 'baseline', 'findings', 'fix', 'result']) {
      await page.goto(`${base}/demo?step=${step}`)
      await page.getByText("You're looking at a real, saved run", { exact: true }).waitFor()
      await page.evaluate(() => document.fonts.ready)
      if (step === 'baseline') assert(await page.getByText('$0.2244', { exact: true }).count(), 'The app retains its more precise cost display')
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${width}px ${step}: product layout`)
      const smallProductCopy = await page.locator('main *').evaluateAll(elements => elements.filter(el => el.getBoundingClientRect().width > 0 && el.getBoundingClientRect().height > 0 && [...el.childNodes].some(node => node.nodeType === Node.TEXT_NODE && node.textContent.trim()) && Number.parseFloat(getComputedStyle(el).fontSize) < 14).map(el => el.textContent.trim().slice(0, 80)))
      assert.deepEqual(smallProductCopy, [], `${width}px ${step}: product copy is at least 14px`)
      assert(await page.locator('.slab').evaluateAll(elements => elements.every(el => getComputedStyle(el).borderTopWidth === '0px' && getComputedStyle(el).boxShadow === 'none')), `${width}px ${step}: app reading groups stay flat`)
      await page.evaluate(scanner)
      const scan = await page.evaluate(() => window.__wd.scan({ app: true }))
      if (scan.fails.length) await page.screenshot({ path: path.join(out, `failure-app-${step}-${width}.png`), fullPage: true })
      assert.deepEqual(scan.fails, [], `${width}px ${step}: shared light-theme contrast`)
      if (step === 'result') await page.screenshot({ path: path.join(out, `app-result-${width}.png`), fullPage: true })
    }
  }
  await page.getByRole('link', { name: 'Hansa home' }).click()
  await page.locator('.hero-actions .button-primary').click()
  await page.waitForURL('**/sign-in')

  // Virtual time checks the complete 7.2-second loop without waiting for every cycle.
  const loop = await context.newPage()
  loop.on('pageerror', error => errors.push(error.message))
  await loop.clock.install()
  await loop.clock.pauseAt(new Date(Date.now() + 1000))
  await loop.goto(base)
  await loop.locator('.diagram-actions').waitFor()
  await loop.evaluate(() => document.fonts.ready)
  await loop.clock.runFor(300)
  await loop.locator('.experiment-diagram').evaluate(el => el.getAnimations().forEach(animation => animation.finish()))
  const stages = loop.locator('.experiment-diagram [data-active]')
  const selected = () => stages.evaluateAll(elements => elements.findIndex(el => el.dataset.active === 'true'))
  assert.deepEqual(await stages.locator(':scope > span').allTextContents(), ['Patch', 'Measurements', 'Verdict'])
  assert.equal(await selected(), 0)
  const highlight = await stages.first().evaluate(el => {
    const style = getComputedStyle(el, '::before')
    return [style.transitionProperty, style.transitionDuration]
  })
  assert.deepEqual(highlight, ['opacity', '0.3s'], 'Highlights crossfade through an opacity layer')
  assert.equal(await stages.first().evaluate(el => getComputedStyle(el, '::before').backgroundColor), 'rgb(228, 244, 241)', 'Highlights use the teal wash')
  assert.equal(await loop.locator('.experiment-diagram button').count(), 0, 'The diagram has no playback button')
  const bounds = await loop.locator('.experiment-diagram').boundingBox()
  for (const index of [1, 2, 3, 4, 5, 0]) {
    await loop.clock.runFor(1200)
    assert.equal(await selected(), index, 'Investigate → Edit → Test → Patch → Measurements → Verdict → repeat')
    assert.equal(await loop.locator('.experiment-diagram [data-active=true]').count(), 1)
    assert.deepEqual(await loop.locator('.experiment-diagram').boundingBox(), bounds, 'Highlighting never shifts the diagram')
    if (index === 5) {
      await loop.clock.runFor(300)
      await loop.screenshot({ path: path.join(out, 'hero-loop-verdict.png') })
    }
  }
  await loop.locator('.experiment-diagram').hover()
  await loop.clock.runFor(9000)
  assert.equal(await selected(), 0, 'Hover holds the current stage')
  await loop.mouse.move(0, 0)
  await loop.clock.runFor(1200)
  assert.equal(await selected(), 1, 'Leaving resumes the loop')
  await loop.locator('.experiment-diagram').focus()
  await loop.clock.runFor(9000)
  assert.equal(await selected(), 1, 'Keyboard focus pauses too')
  await loop.locator('.hero-actions a').first().focus()
  await loop.clock.runFor(1200)
  assert.equal(await selected(), 2, 'Leaving focus resumes the loop')
  await loop.emulateMedia({ reducedMotion: 'reduce' })
  await loop.waitForFunction(() => !document.querySelector('.experiment-diagram [data-active=true]'))
  await loop.clock.runFor(9000)
  assert.equal(await selected(), -1, 'Reduced motion shows a static diagram')
  await loop.emulateMedia({ reducedMotion: 'no-preference' })
  await loop.locator('.experiment-diagram [data-active=true]').waitFor()
  assert.equal(await selected(), 2, 'Reduced motion retains the last stage without advancing')
  await loop.clock.runFor(1200)
  assert.equal(await selected(), 3, 'A changed motion preference resumes the loop')

  // Autoplay starts only once the demo tabs are visible; values are presentation only.
  await loop.goto(base)
  await loop.locator('.demo-tabs').waitFor()
  const selectedTab = () => loop.locator('.demo-tabs [aria-selected=true]').getAttribute('aria-label')
  await loop.clock.runFor(12000)
  assert.equal(await selectedTab(), 'Baseline', 'Offscreen demo stays on Baseline')
  await loop.locator('.demo-tabs').scrollIntoViewIfNeeded()
  await loop.locator('.demo-tabs[data-advancing=true]').waitFor()
  const progressLine = await loop.locator('.demo-tabs [aria-selected=true]').evaluate(el => {
    const style = getComputedStyle(el, '::after')
    return [style.animationName, style.animationDuration, style.height]
  })
  assert.deepEqual(progressLine, ['demo-progress', '5s', '2px'])
  for (const label of ['Findings', 'Tested change', 'Verdict']) {
    await loop.clock.runFor(5000)
    assert.equal(await selectedTab(), label, 'Demo advances through the saved story')
  }
  const candidate = loop.locator('.candidate-measurement')
  const values = () => candidate.evaluateAll(elements => elements.map(el => Number(el.dataset.value)))
  const original = ['model_calls', 'cost_usd', 'wall_time_seconds'].map(key => report.optimizations.at(-1).comparison.totals[key].baseline)
  const target = ['model_calls', 'cost_usd', 'wall_time_seconds'].map(key => report.optimizations.at(-1).comparison.totals[key].candidate)
  assert.deepEqual(await values(), original, 'Candidate figures start from the saved baseline')
  const comparisonBounds = await loop.locator('.demo-comparison').boundingBox()
  await loop.clock.runFor(350)
  const midway = await values()
  midway.forEach((value, index) => assert(value < original[index] && value > target[index], 'Figures tick between saved endpoints'))
  await loop.clock.runFor(900)
  assert.deepEqual(await values(), target, 'Figures finish exactly at the saved candidate')
  assert.deepEqual(await loop.locator('.demo-comparison').boundingBox(), comparisonBounds, 'Ticking keeps the comparison stable')
  await loop.clock.runFor(3750)
  assert.equal(await selectedTab(), 'Baseline', 'The automatic story loops')
  await loop.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: true }); document.dispatchEvent(new Event('visibilitychange')) })
  await loop.locator('.demo-tabs[data-advancing=false]').waitFor()
  await loop.clock.runFor(12000)
  assert.equal(await selectedTab(), 'Baseline', 'A simulated hidden document pauses autoplay')
  await loop.evaluate(() => { delete document.hidden; document.dispatchEvent(new Event('visibilitychange')) })
  await loop.locator('.demo-tabs[data-advancing=true]').waitFor()
  await loop.locator('.demo-tabs').hover()
  await loop.clock.runFor(5000)
  assert.equal(await selectedTab(), 'Findings', 'Hover does not stall the five-second phases')
  await loop.mouse.move(0, 0)
  await loop.clock.runFor(5000)
  assert.equal(await selectedTab(), 'Tested change')
  await loop.getByRole('tab', { name: 'Baseline', exact: true }).click()
  await loop.mouse.move(0, 0)
  await loop.clock.runFor(20000)
  assert.equal(await selectedTab(), 'Baseline', 'Clicking a tab permanently stops autoplay')
  assert.equal(await loop.locator('.demo-tabs').getAttribute('data-advancing'), 'false')
  await loop.getByRole('tab', { name: 'Verdict', exact: true }).click()
  assert.deepEqual(await values(), original, 'Manual results animate too')
  await loop.emulateMedia({ reducedMotion: 'reduce' })
  await loop.waitForFunction(expected => document.querySelector('.candidate-measurement')?.getAttribute('data-value') === String(expected), target[0])
  assert.deepEqual(await values(), target, 'Reduced motion shows final values immediately')

  await loop.goto(base)
  await loop.mouse.move(0, 0)
  await loop.locator('.demo-tabs').scrollIntoViewIfNeeded()
  await loop.clock.runFor(20000)
  assert.equal(await selectedTab(), 'Baseline', 'Reduced motion disables demo autoplay')
  await loop.emulateMedia({ reducedMotion: 'no-preference' })
  await loop.locator('.demo-tabs[data-advancing=true]').waitFor()
  await loop.getByRole('tab', { name: 'Baseline', exact: true }).focus()
  await loop.keyboard.press('ArrowRight')
  await loop.locator('.hero-actions a').first().focus()
  await loop.clock.runFor(20000)
  assert.equal(await selectedTab(), 'Findings', 'Keyboard selection also permanently stops autoplay')
  await loop.close()
  assert.deepEqual(requests, [], 'Browsing must not dispatch jobs or read private GitHub endpoints.')
  assert.deepEqual(errors, [])
  const logo = await fs.readFile(new URL('../public/brand/mark.svg', import.meta.url), 'utf8')
  assert(logo.includes('Hansa swan'))
  assert.equal(logo, await fs.readFile(new URL('../public/favicon.svg', import.meta.url), 'utf8'))
  console.log(`Landing passed: demo autoplay/progress, click/keyboard takeover, animated saved figures, reduced motion, six-stage hero loop, hover/focus pause, stable highlights, proof-first order, app precision, saved evidence, source links, navigation, contrast and 320–1440px layouts. Screenshots: ${out}. No live runs started.`)
} finally {
  await browser.close()
}
